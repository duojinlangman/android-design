    val books: List<Pair<String, String>>
        get() = listOf("四级核心词" to CET4, "日常高频词" to DAILY)

    private fun parse(raw: String): List<Word> = raw.trim().lines().filter { it.isNotBlank() }.map { line ->
        val parts = line.trim().split("|")
        Word(
            word = parts[0].trim(),
            phonetic = parts.getOrElse(1) { "" }.trim(),
            meaning = parts.getOrElse(2) { "" }.trim()
        )
    }

    fun wordsOf(index: Int): List<Word> = parse(if (index == 0) CET4 else DAILY)

